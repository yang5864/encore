/** 나쁜 소식 상황: 분위기가 좋은 문장·티저 기대 문장이 섞이지 않도록 시대 말투도 부정 톤만 쓴다. */
const BAD_KINDS: ReactionKind[] = ["scandal", "scandal-bullying", "scandal-dating", "scandal-dui", "scandal-live", "scandal-chart", "hate-sasaeng", "health", "injury", "feud", "cut", "kpi-miss", "bankrupt", "comeback-after-scandal"];

export type ReactionContext = { kind: ReactionKind; album?: string; show?: string; melon?: number | null; /** 이벤트 id: 상황이 generic일 때 EVENT_LINES에서 고른다 */ event?: string };

function fill(text: string, c: Career, ctx: ReactionContext): string {
  return text
    .replaceAll("{g}", c.groupName || c.name)
    .replaceAll("{n}", c.name)
    .replaceAll("{a}", ctx.album ?? "이번 앨범")
    .replaceAll("{s}", ctx.show ?? "음악방송")
    .replaceAll("{m}", ctx.melon !== null && ctx.melon !== undefined ? String(ctx.melon) : "?")
    .replaceAll("{y}", String(yearOf(c)));
}

/** 공개된 순간의 댓글 3개: 상황 문장 2 + 같은 톤 반응 1. */
export function buildReactions(c: Career, tone: "good" | "bad" | "neutral", ctx: ReactionContext = { kind: "generic" }): Comment[] {
  const byEvent = ctx.kind === "generic" && ctx.event ? EVENT_LINES[ctx.event] : undefined;
  const base = byEvent ? byEvent[tone === "bad" ? "bad" : "good"] : S[ctx.kind] ?? S.generic;
  const situational = base.filter((t) => !(t.includes("{m}") && (ctx.melon === null || ctx.melon === undefined)));
  // 나쁜 소식에는 들뜬 반응이 섞이지 않게 한다
  const flavor = TONE[BAD_KINDS.includes(ctx.kind) && tone !== "bad" ? "bad" : tone];
  const used = new Set<string>();
  const authors = new Set<string>();
  const out: Comment[] = [];
  const scale = Math.max(30, Math.sqrt(c.fans + 100) * 3);
  const take = (pool: string[]) => {
    for (let i = 0; i < 12; i++) {
      const text = pick(c, pool);
      if (used.has(text)) continue;
      used.add(text);
      let author = pick(c, AUTHORS);
      for (let j = 0; j < 6 && authors.has(author); j++) author = pick(c, AUTHORS);
      authors.add(author);
      out.push({ author, text: fill(text, c, ctx), likes: Math.round(scale * (0.4 + rng(c) * 1.8)) });
      return;
    }
  };
  take(situational);
  take(situational);
  take(flavor);
  // 톤 문장은 중간에 섞는다
  if (out.length === 3) [out[1], out[2]] = [out[2], out[1]];
  return out;
}

export function likeText(n: number): string {
  if (n < 1000) return `${n}`;
  if (n < 10000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}천`;
  return `${(n / 10000).toFixed(1).replace(/\.0$/, "")}만`;
}

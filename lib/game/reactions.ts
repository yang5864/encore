export type ReactionContext = { kind: ReactionKind; album?: string; show?: string; melon?: number | null };

function fill(text: string, c: Career, ctx: ReactionContext): string {
  return text
    .replaceAll("{g}", c.groupName || c.name)
    .replaceAll("{n}", c.name)
    .replaceAll("{a}", ctx.album ?? "이번 앨범")
    .replaceAll("{s}", ctx.show ?? "음악방송")
    .replaceAll("{m}", ctx.melon !== null && ctx.melon !== undefined ? String(ctx.melon) : "?")
    .replaceAll("{y}", String(yearOf(c)));
}

/** 3 in-game comments for a public moment: 상황 2 + 시대 말투 1. */
export function buildReactions(c: Career, tone: "good" | "bad" | "neutral", ctx: ReactionContext = { kind: "generic" }): Comment[] {
  const era = eraOf(yearOf(c));
  const situational = (S[ctx.kind] ?? S.generic).filter((t) => !(t.includes("{m}") && (ctx.melon === null || ctx.melon === undefined)));
  const flavor = ERA[era][tone];
  const used = new Set<string>();
  const out: Comment[] = [];
  const scale = Math.max(30, Math.sqrt(c.fans + 100) * 3);
  const take = (pool: string[]) => {
    for (let i = 0; i < 10; i++) {
      const text = pick(c, pool);
      if (used.has(text)) continue;
      used.add(text);
      out.push({ author: pick(c, AUTHORS[era]), text: fill(text, c, ctx), likes: Math.round(scale * (0.4 + rng(c) * 1.8)) });
      return;
    }
  };
  take(situational);
  take(situational);
  take(flavor);
  // 시대 문장은 중간에 섞는다
  if (out.length === 3) [out[1], out[2]] = [out[2], out[1]];
  return out;
}

export function likeText(n: number): string {
  if (n < 1000) return `${n}`;
  if (n < 10000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}천`;
  return `${(n / 10000).toFixed(1).replace(/\.0$/, "")}만`;
}
